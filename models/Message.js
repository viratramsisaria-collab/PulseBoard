import mongoose from "mongoose";

const MessageSchema = new mongoose.Schema(
  {
    workspace: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Workspace",
      required: true,
      index: true,
    },

    sender: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    content: {
      type: String,
      required: true,
      trim: true,
      maxlength: 2000,
    },
  },
  {
    timestamps: true,
  }
);

MessageSchema.index({
  workspace: 1,
  createdAt: -1,
});

export default mongoose.models.Message ||
  mongoose.model("Message", MessageSchema);